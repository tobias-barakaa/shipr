package testutil

import (
	"os"
	"strconv"
	"strings"
)

// ProcessAlive reports whether pid exists and is not a zombie (Linux /proc).
func ProcessAlive(pid int) bool {
	data, err := os.ReadFile("/proc/" + strconv.Itoa(pid) + "/stat")
	if err != nil {
		return false
	}
	s := string(data)
	i := strings.LastIndexByte(s, ')')
	if i < 0 || i+2 >= len(s) {
		return false
	}
	return s[i+2] != 'Z'
}
